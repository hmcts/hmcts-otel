"""Regenerate docs/conventions.md from the core schema. CI fails if it is out of date."""

from __future__ import annotations

import sys
from pathlib import Path

from hmcts_otel import TelemetrySchema
from hmcts_otel import conventions as c

HEADER = f"""# Telemetry conventions

Generated by `scripts/generate_conventions.py` from `hmcts_otel/schema.py`. Do not edit by hand.

These are the core attributes every service gets. Services register their own
attributes and events in their schema and should publish the same table, using
`default_schema.to_markdown()`.

## Naming

- Attribute, event and stage names: lower-case dotted snake case, e.g. `speech.cancel_reason`.
- Events from a stage: `<stage>.started`, `<stage>.completed`, `<stage>.failed`, `<stage>.cancelled`.
- Error codes: controlled values such as `speech.timeout`, never messages.
- Identifiers: system-generated (UUIDs). Never case references, file names, names or emails.

## Metrics

| Metric | Type | Unit | Dimensions |
|---|---|---|---|
| `{c.METRIC_STAGE_DURATION}` | histogram | s | `{c.STAGE}`, `{c.OUTCOME}`, `{c.ERROR_CODE}`, `{c.JOURNEY_TYPE}` |
| `{c.METRIC_EVENTS}` | counter | event | `event`, `class`, `source` |
| `{c.METRIC_EVENT_DURATION}` | histogram | s | `event`, `class`, `source` |
| `{c.METRIC_DROPPED_ATTRIBUTES}` | counter | attribute | `reason`, `where` |
| `{c.METRIC_TELEMETRY_ERRORS}` | counter | error | `kind` (`invalid.*` misuse, `internal.*` failures) |

Duration histograms use bucket boundaries (seconds): `{", ".join(str(b) for b in c.DURATION_BUCKETS_S)}`.
In App Insights only count, sum, min and max are kept; compute percentiles from events.

Journey IDs are never metric dimensions.

## Core attributes

"""

if __name__ == "__main__":
    text = HEADER + TelemetrySchema().to_markdown()
    target = Path(__file__).resolve().parent.parent / "docs" / "conventions.md"
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != text:
            sys.exit("docs/conventions.md is out of date: run python scripts/generate_conventions.py")
    else:
        target.write_text(text)
